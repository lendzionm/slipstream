export type Lang = "pl" | "en";
export type TextKey = keyof typeof en;
const dictionaries = { en, pl };

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "en",
  setLang: () => {},
});

// Wrap the whole app in this so every screen knows the current language.
// The app starts in English; the PL | EN switch changes it.
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

// Use inside any screen: const { t } = useLang();  then  t("race")
// Texts with {placeholders}: t("agreement", { x: 3 })
export function useLang() {
  const { lang, setLang } = useContext(LangContext);
  const t = (key: TextKey, vars?: Record<string, string | number>) => {
    let text: string = dictionaries[lang][key];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
    }
    return text;
  };
  const locale = lang === "pl" ? "pl-PL" : "en-GB";
  return { lang, setLang, t, locale };
}
